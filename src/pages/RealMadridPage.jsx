function RealMadridPage() {
  const [galleryVisible, setGalleryVisible] = useState(false)
  const [activeIndex, setActiveIndex] = useState(null)

  const toggleGallery = () => {
    setGalleryVisible(!galleryVisible)
  }

  const toggleAccordion = (index) => {
    setActiveIndex(activeIndex === index ? null : index)
  }

  return (
    <div className="real-madrid-page">
      <h1>⚽ Real Madrid</h1>
      <p>Стадион Сантьяго Бернабеу</p>

      {/* Кнопка "На главную" */}
      <Link to="/" className="back-button">
        <i className="fas fa-home"></i> На главную
      </Link>

      {/* Кнопка "Фотогалерея" */}
      <button className="gallery-toggle-btn" onClick={toggleGallery}>
        {galleryVisible ? (
          <>
            <i className="fas fa-times"></i> Закрыть галерею
          </>
        ) : (
          <>
            <i className="fas fa-camera"></i> Фотогалерея
          </>
        )}
      </button>

      {/* Аккордеон со снимками */}
      {galleryVisible && (
        <div className="accordion">
          {accordionData.map((item, index) => (
            <div key={index} className="accordion-item">
              <button
                className={`accordion-header ${activeIndex === index ? 'active' : ''}`}
                onClick={() => toggleAccordion(index)}
              >
                {item.title}
              </button>
              <div
                className={`accordion-content ${activeIndex === index ? 'show' : ''}`}
              >
                <img src={item.image} alt={item.h3} className="accordion-img" />
                <div className="description">
                  <h3>{item.h3}</h3>
                  <p>{item.p}</p>
                </div>
              </div>
            </div>
          ))}
        </div>
      )}
    </div>
  )
}

export default RealMadridPage
